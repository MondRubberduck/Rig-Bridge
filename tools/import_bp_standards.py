"""Generate rig_bridge/standards/standards.json from Bulletproof Retarget.

Bulletproof Retarget (separate add-on, same author) owns the skeleton-standard
tables. This script only READS its source: it imports skeletons.py and
standards.py from a checkout without running the add-on (no bpy needed) and
writes the data Rig Bridge needs to detect the same standards. Nothing in the
retarget add-on is changed, and Rig Bridge does not need it installed.

    python tools/import_bp_standards.py <path to Bulletproof-Retarget checkout>
"""

import importlib
import json
import os
import subprocess
import sys
import types

sys.dont_write_bytecode = True   # never leave files in the retarget checkout

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "standards", "standards.json")

# These standards already ARE control rigs: Rig Bridge must not add another
# layer on top, it tells the user to animate them directly.
CONTROL_RIGS = {"P2M", "RIGIFY", "ARP_RIG", "ARP_FK"}


def load(repo):
    pkg_dir = os.path.join(repo, "bulletproof_retarget")
    if not os.path.isfile(os.path.join(pkg_dir, "standards.py")):
        raise SystemExit(f"not a Bulletproof Retarget checkout: {repo}")
    # A stand-in package so the add-on's __init__ (which needs bpy) never runs.
    pkg = types.ModuleType("_bpr_readonly")
    pkg.__path__ = [pkg_dir]
    sys.modules["_bpr_readonly"] = pkg
    sk = importlib.import_module("_bpr_readonly.skeletons")
    st = importlib.import_module("_bpr_readonly.standards")
    return sk, st


def commit(repo):
    try:
        return subprocess.check_output(["git", "-C", repo, "rev-parse", "--short", "HEAD"], text=True).strip()
    except Exception:
        return ""


def main():
    repo = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else ".")
    sk, st = load(repo)
    with open(os.path.join(repo, "bulletproof_retarget", "blender_manifest.toml"), encoding="utf-8") as fh:
        version = next((ln.split("=", 1)[1].strip().strip('"') for ln in fh if ln.startswith("version")), "")
    defs = list(sk.DEFINITIONS) + [d for d in st.ALL if d.id not in sk.BY_ID]
    out = {
        "source": {"addon": "Bulletproof Retarget", "version": version, "commit": commit(repo),
                   "note": "generated by tools/import_bp_standards.py - do not edit by hand"},
        "matcher": {
            "core_joints": list(sk.CORE_JOINTS),
            "threshold": 0.75,
            "exclude_factor": st.EXCLUDE_FACTOR,
            "asset_seps": sk._ASSET_SEPS,
            "asset_min_bones": sk._ASSET_MIN_BONES,
            "not_asset_re": sk._NOT_ASSET_RE.pattern,
            "body_word_re": sk._BODY_WORD_RE.pattern,
        },
        "standards": [],
    }
    for d in defs:
        e = {
            "id": d.id, "name": d.name, "short": d.short, "description": d.description,
            "kind": "standard" if isinstance(d, st.StandardDef) else "base",
            "bones": {k: list(v) for k, v in d.bones.items()},
            "signature": list(d.signature),
            "control_rig": d.id in CONTROL_RIGS,
        }
        if isinstance(d, st.StandardDef):
            e.update(sig_need=d.sig_need, exclude=list(d.exclude), require=list(d.require),
                     exclude_re=d.exclude_re.pattern if d.exclude_re else "", bias=d.bias,
                     asset_joint=d.asset_joint or "", confidence=d.confidence)
        out["standards"].append(e)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=1, ensure_ascii=False)
    print(f"wrote {len(out['standards'])} standards from Bulletproof Retarget {version} ({out['source']['commit']})"
          f" -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
